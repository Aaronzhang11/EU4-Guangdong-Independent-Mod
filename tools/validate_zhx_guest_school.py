        "zhx_guest_school_send_home_tt",
        "zhx_guest_school_expel_cost_tt",
        "zhx_guest_school.reminder.t",
        "zhx_guest_school.reminder.d",
        "zhx_guest_school.reminder.no_source.d",
        "zhx_guest_school.expiry.t",
        "zhx_guest_school.expiry.d",
        "zhx_guest_school.expiry.no_source.d",
        "zhx_guest_school.expel.t",
        "zhx_guest_school.expel.d",
        "zhx_guest_school.expel.no_source.d",
