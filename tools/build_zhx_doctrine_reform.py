def indent(text: str, spaces: int = 4) -> str:
    prefix = " " * spaces
    return "\n".join(prefix + line if line else line for line in text.splitlines())


def or_block(lines: list[str], spaces: int = 0) -> str:
    pad = " " * spaces
    body = "\n".join(f"{pad}    {line}" for line in lines)
    return f"{pad}OR = {{\n{body}\n{pad}}}"


def academy_root_body(code: str) -> str:
    modifiers = SCHOOLS[code]["academies"]
    provinces = [
        "AND = { "
        f"has_province_modifier = {modifier} "
        "NOT = { has_province_modifier = zhx_academy_under_expulsion } "
        "}"
        for modifier in modifiers
    ]
    return (
        "any_owned_province = {\n"
        + indent(or_block(provinces), 4)
        + "\n}"
    )


