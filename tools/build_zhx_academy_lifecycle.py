def offer_effect(entry: dict[str, object], *, refugee: bool) -> str:
    key = entry["key"]
    school = str(entry["school"])
    name = f"zhx_academy_offer_{'refuge' if refugee else 'revival'}_{key}"
    tiers = ["main", "invited", "friendly" if refugee else "any"]
    blocks = []
    for index, tier in enumerate(tiers):
        limit = candidate_limit(school, tier, refugee=refugee)
        keyword = "if" if index == 0 else "else_if"
        blocks.append(
            f"""    {keyword} = {{
        limit = {{
            any_country = {{
{indent(limit, 16)}
            }}
        }}
        random_country = {{
            limit = {{
{indent(limit, 16)}
            }}
            set_country_flag = zhx_academy_refuge_offer_pending
            set_country_flag = zhx_academy_refuge_offer_{key}
            country_event = {{ id = zhx_academy.210 }}
        }}
    }}"""
        )
    return f"{name} = {{\n" + "\n".join(blocks) + "\n}"


