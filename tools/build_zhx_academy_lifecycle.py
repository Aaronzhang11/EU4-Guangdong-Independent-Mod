def indent(text: str, spaces: int = 4) -> str:
    prefix = " " * spaces
    return "\n".join(prefix + line if line else line for line in text.splitlines())


def load_academies() -> list[dict[str, object]]:
    payload = json.loads(MANIFEST.read_text(encoding="utf-8"))
    academies = payload["academies"]
    if len(academies) != 12:
        raise ValueError(f"expected 12 opening academies, found {len(academies)}")
    keys = [str(entry["key"]) for entry in academies]
    modifiers = [str(entry["modifier"]) for entry in academies]
    if len(set(keys)) != len(keys) or len(set(modifiers)) != len(modifiers):
        raise ValueError("academy keys and active modifiers must be unique")
    unknown = sorted({str(entry["school"]) for entry in academies} - set(SCHOOLS))
    if unknown:
        raise ValueError(f"unknown academy schools: {', '.join(unknown)}")
    return academies


def or_block(lines: list[str], level: int = 0) -> str:
    pad = " " * level
    inner = "\n".join(f"{pad}    {line}" for line in lines)
    return f"{pad}OR = {{\n{inner}\n{pad}}}"


def protection_trigger(school: str) -> str:
    meta = SCHOOLS[school]
    return (
        "OR = {\n"
        f"    has_country_flag = {meta['flag']}\n"
        f"    has_country_modifier = {meta['invited']}\n"
        "}"
    )


def candidate_limit(school: str, tier: str, *, refugee: bool) -> str:
    meta = SCHOOLS[school]
    lines = [
        "exists = yes",
        "zhx_is_lijiao_country = yes",
        "zhx_academy_has_empty_host_province = yes",
        "NOT = { has_country_flag = zhx_academy_refuge_offer_pending }",
    ]
    if refugee:
        lines.append("NOT = { tag = event_target:zhx_academy_expeller }")
    if tier == "main":
        lines.append(f"has_country_flag = {meta['flag']}")
    elif tier == "invited":
        lines.append(f"has_country_modifier = {meta['invited']}")
    elif tier == "friendly":
        lines.append(
            "has_opinion = { who = event_target:zhx_academy_expeller value = 50 }"
        )
    elif tier != "any":
        raise ValueError(tier)
    return "\n".join(lines)


def render_triggers(academies: list[dict[str, object]]) -> str:
    active = [f"has_province_modifier = {entry['modifier']}" for entry in academies]
    ruins = [
        f"has_province_modifier = zhx_academy_ruins_{entry['key']}"
        for entry in academies
    ]
    sections = [
        "# Generated by tools/build_zhx_academy_lifecycle.py. Do not hand-edit.",
        "# Active academy truth is the unique permanent province modifier.",
        "",
        "zhx_academy_is_active_province = {\n"
        + indent(or_block(active), 4)
        + "\n}",
        "",
        "zhx_academy_is_former_site = {\n"
        + indent(or_block(ruins), 4)
        + "\n}",
        "",
        "zhx_academy_is_empty_host_province = {\n"
        "    is_city = yes\n"
        "    NOT = { zhx_academy_is_active_province = yes }\n"
        "    NOT = { zhx_academy_is_former_site = yes }\n"
        "    NOT = { has_province_modifier = zhx_academy_under_expulsion }\n"
        "}",
        "",
        "zhx_academy_has_empty_host_province = {\n"
        "    any_owned_province = { zhx_academy_is_empty_host_province = yes }\n"
        "}",
    ]

    for entry in academies:
        key = entry["key"]
        school = str(entry["school"])
        sections.extend(
            [
                "",
                f"zhx_academy_has_unprotected_{key} = {{\n"
                f"    any_owned_province = {{ has_province_modifier = {entry['modifier']} }}\n"
                f"    NOT = {{ has_country_flag = {SCHOOLS[school]['flag']} }}\n"
                f"    NOT = {{ has_country_modifier = {SCHOOLS[school]['invited']} }}\n"
                "}",
            ]
        )

    unprotected_province_lines = []
    for entry in academies:
        school = str(entry["school"])
        unprotected_province_lines.append(
            "AND = { "
            f"has_province_modifier = {entry['modifier']} "
            "owner = { "
            f"NOT = {{ has_country_flag = {SCHOOLS[school]['flag']} }} "
            f"NOT = {{ has_country_modifier = {SCHOOLS[school]['invited']} }} "
            "} }"
        )
    sections.extend(
        [
            "",
            "zhx_academy_is_unprotected_active_province = {\n"
            + indent(or_block(unprotected_province_lines), 4)
            + "\n}",
            "",
            "zhx_academy_has_any_unprotected = {\n"
            "    any_owned_province = { zhx_academy_is_unprotected_active_province = yes }\n"
            "}",
        ]
    )

    pair_lines = [
        "AND = { "
        f"zhx_has_unprotected_{left}_academy = yes "
        f"zhx_has_unprotected_{right}_academy = yes "
        "}"
        for left, right in combinations(SCHOOLS, 2)
    ]
    sections.extend(
        [
            "",
            "zhx_academy_has_two_unprotected_school_types = {\n"
            + indent(or_block(pair_lines), 4)
            + "\n}",
            "",
            "zhx_academy_has_any_dormant = {\n"
            + indent(
                or_block(
                    [
                        f"has_global_flag = zhx_academy_dormant_{entry['key']}"
                        for entry in academies
                    ]
                ),
                4,
            )
            + "\n}",
        ]
    )
    return "\n".join(sections) + "\n"


