def render_all() -> dict[Path, str]:
    return {
        TARGETS["triggers"]: render_triggers(),
        TARGETS["effects"]: render_effects(),
        TARGETS["modifiers"]: render_modifiers(),
        TARGETS["opinions"]: render_opinions(),
        TARGETS["decisions"]: render_decisions(),
        TARGETS["events"]: render_events(),
    }


def run(check: bool) -> None:
    outputs = render_all()
    stale: list[str] = []
    for path, text in outputs.items():
        text = text.rstrip() + "\n"
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    if stale:
        raise ValueError("stale guest-school outputs: " + ", ".join(stale))
    print(
        f"{'checked' if check else 'built'} guest-school contract: "
        f"schools={len(SCHOOLS)}, outputs={len(outputs)}, term=7300 days"
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    run(args.check)


if __name__ == "__main__":
    main()
